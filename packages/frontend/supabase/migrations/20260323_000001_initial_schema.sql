create or replace function public.normalize_car_fields()
returns trigger
language plpgsql
as $$
begin
    if new.slug is null or btrim(new.slug) = '' then
        new.slug = public.slugify(new.name);
    else
        new.slug = public.slugify(new.slug);
    end if;

    if coalesce(new.price_per_day, 0) = 0 and coalesce(new.price, 0) > 0 then
        new.price_per_day = new.price;
    end if;

    if coalesce(new.price, 0) = 0 and coalesce(new.price_per_day, 0) > 0 then
        new.price = new.price_per_day;
    end if;

    if new.available is null then
        new.available = new.is_available;
    end if;

    if coalesce(new.status, '') = '' then
        new.status = case when coalesce(new.available, true) then 'available' else 'unavailable' end;
    end if;

    new.updated_at = now();
    return new;
end;
$$;

